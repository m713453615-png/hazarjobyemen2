const arToEn = new Map(pairs)
const enToAr = new Map(pairs.map(([ar, en]) => [en, ar]))
const attributes = ['placeholder', 'title', 'aria-label']

function translateValue(value: string, language: AppLanguage) {
  const leading = value.match(/^\s*/)?.[0] ?? ''
  const trailing = value.match(/\s*$/)?.[0] ?? ''
  const core = value.trim()
  if (!core) return value
  const translated = language === 'en' ? arToEn.get(core) : enToAr.get(core)
  return translated ? `${leading}${translated}${trailing}` : value
}

function translateRoot(root: ParentNode, language: AppLanguage) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT)
  let node = walker.nextNode()
  while (node) {
    const parent = node.parentElement
    if (parent && !['SCRIPT', 'STYLE', 'TEXTAREA'].includes(parent.tagName) && !parent.isContentEditable) {
      const next = translateValue(node.textContent ?? '', language)
      if (next !== node.textContent) node.textContent = next
    }
    node = walker.nextNode()
  }

  root.querySelectorAll<HTMLElement>('*').forEach(element => {
    attributes.forEach(attribute => {
      const value = element.getAttribute(attribute)
      if (!value) return
      const next = translateValue(value, language)
      if (next !== value) element.setAttribute(attribute, next)
    })
  })
}

export function useInterfaceLanguage(language: AppLanguage) {
  useEffect(() => {
    document.documentElement.lang = language
    document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr'
    document.body.dataset.language = language
    localStorage.setItem('hazar-language', JSON.stringify(language))

    let translating = false
    const apply = () => {
      if (translating) return
      translating = true
      translateRoot(document.body, language)
      translating = false
    }

    apply()
    const observer = new MutationObserver(apply)
    observer.observe(document.body, {
      childList: true,
      subtree: true,
      characterData: true,
      attributes: true,
      attributeFilter: attributes,
    })
    return () => observer.disconnect()
  }, [language])
}
